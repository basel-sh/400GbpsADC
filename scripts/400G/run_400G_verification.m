function c=make_cfg(q,bits,loss,noise_mV,jitter_fs,de)
c=config_400G(struct('mod',struct('order',q),'dac',struct('bits',bits), ...
 'adc',struct('bits',bits),'channel',struct('main_loss_dB_at_f',loss)));
c.dac.clip_ratio_dB=12.6;c.adc.clip_ratio_dB=13.4;
c.noise.reference='channel_output';c.noise.rx_input_rms_V=noise_mV*1e-3;
c.jitter.rms_UI=jitter_fs*1e-15*c.fs;c.jitter.method='spectral_linear';
c.deemph.k1_dB=de;c.deemph.k511_dB=0;c.deemph.gain_dB=@(k)de*(511-k)/510;
assert(abs(c.achieved_data_rate_bps/400e9-1)<1e-12);
assert(c.dac.clip_ratio_dB==12.6 && c.adc.clip_ratio_dB==13.4);
end
function s=pack(name,c,r,seed)
q=c.mod.order;
b1=qam_demodulate(r.tx_syms1,q);z1=qam_demodulate(r.rx_syms1,q);
b2=qam_demodulate(r.tx_syms2,q);z2=qam_demodulate(r.rx_syms2,q);
s=struct('name',name,'seed',seed,'qam',q,'bits',c.adc.bits, ...
 'rate_Gbps',c.achieved_data_rate_bps/1e9,'fs_GSs',c.fs/1e9,'bandwidth_GHz',c.fs/2e9, ...
 'channel_type',c.channel.type,'synthetic_loss40_dB',c.channel.main_loss_dB_at_f, ...
 'noise_mV',c.noise.rx_input_rms_V*1e3,'noise_reference',c.noise.reference, ...
 'jitter_fs',c.jitter.rms_UI/c.fs*1e15,'jitter_method',c.jitter.method, ...
 'deemphasis_low_dB',c.deemph.k1_dB,'L',c.chest.L_moving_avg, ...
 'dac_clip_dB',c.dac.clip_ratio_dB,'adc_clip_dB',c.adc.clip_ratio_dB, ...
 'ber',r.ber,'ber_lane1',mean(b1~=z1),'ber_lane2',mean(b2~=z2), ...
 'ser',r.ser,'ser_without_cancel',r.ser_other_mode, ...
 'bit_errors',r.bit_errors,'num_bits',r.num_bits,'symbol_errors',r.symbol_errors, ...
 'num_symbols',r.num_qam_symbols,'evm_percent',r.evm_percent);
fprintf('%s seed%d Q%d %dbit %.2ffs: BER %.6g SER %.6g errors%d/%d\n', ...
 name,seed,q,c.adc.bits,s.jitter_fs,r.ber,r.ser,r.bit_errors,r.num_bits);
end
function u=upper95(e,n)
% Nominal one-sided Bernoulli bound; OFDM/shared-training correlation is not covered.
if e==0,u=1-0.05^(1/n);return;end
z=1.64485362695147;p=e/n;
u=(p+z^2/(2*n)+z*sqrt(p*(1-p)/n+z^2/(4*n^2)))/(1+z^2/n);
end
